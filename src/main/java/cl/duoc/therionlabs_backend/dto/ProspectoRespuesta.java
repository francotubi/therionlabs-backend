package cl.duoc.therionlabs_backend.dto;

import cl.duoc.therionlabs_backend.entity.Prospecto;

import java.util.UUID;

public record ProspectoRespuesta(
        UUID id,
        UUID eventoId,
        String eventoNombre,
        UUID captadorId,
        String codigoCaptador,
        String captador,
        boolean eliminado,
        String rut,
        String nombre,
        String apellidos,
        String fechaNacimiento,
        String celular,
        String email,
        String establecimiento,
        String comunaResidencia,
        String comunaEstablecimiento,
        String actividadActual,
        String jornada,
        String region,
        String sede,
        String nivelInteres,
        String carrera1,
        String carrera2,
        String carrera3,
        String modalidad,
        String canalContacto,
        String observaciones,
        boolean autorizaContacto,
        Long fechaCaptura,
        String fotoRuta,
        Double latitud,
        Double longitud,
        Float precisionMetros,
        Long fechaUbicacion,
        String direccion) {
    public static ProspectoRespuesta desde(Prospecto datos) {
        return new ProspectoRespuesta(
                datos.getId(),
                datos.getEvento().getId(),
                datos.getEvento().getNombre(),
                datos.getCaptador().getId(),
                datos.getCaptador().getIdentificadorLocal(),
                datos.getCaptador().getNombre(),
                datos.isEliminado(),
                datos.getRut(),
                datos.getNombre(),
                datos.getApellidos(),
                datos.getFechaNacimiento(),
                datos.getCelular(),
                datos.getEmail(),
                datos.getEstablecimiento(),
                datos.getComunaResidencia(),
                datos.getComunaEstablecimiento(),
                datos.getActividadActual(),
                datos.getJornada(),
                datos.getRegion(),
                datos.getSede(),
                datos.getNivelInteres(),
                datos.getCarrera1(),
                datos.getCarrera2(),
                datos.getCarrera3(),
                datos.getModalidad(),
                datos.getCanalContacto(),
                datos.getObservaciones(),
                datos.isAutorizaContacto(),
                datos.getFechaCaptura(),
                datos.getFotoRuta(),
                datos.getLatitud(),
                datos.getLongitud(),
                datos.getPrecisionMetros(),
                datos.getFechaUbicacion(),
                datos.getDireccion());
    }
}
